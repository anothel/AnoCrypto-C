#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <anocrypto/anocrypto.h>

static int failures = 0;

static void expect_status(const char *name, ano_crypto_status_t got, ano_crypto_status_t expected)
{
    if (got != expected) {
        fprintf(stderr, "FAIL %s: got %s expected %s\n",
                name, ano_crypto_status_name(got), ano_crypto_status_name(expected));
        ++failures;
    }
}

static void expect_digest(
    const char *name,
    const uint8_t *input,
    size_t input_len,
    const uint8_t expected[ANO_CRYPTO_OCSP_CERTID_SHA1_DIGEST_SIZE])
{
    uint8_t output[ANO_CRYPTO_OCSP_CERTID_SHA1_DIGEST_SIZE];
    size_t written = 99u;
    ano_crypto_status_t status;

    (void)memset(output, 0xa5, sizeof(output));
    status = ano_crypto_ocsp_certid_sha1_digest(
        input, input_len, output, sizeof(output), &written);
    expect_status(name, status, ANO_CRYPTO_OK);
    if (status == ANO_CRYPTO_OK) {
        if (written != sizeof(output)) {
            fprintf(stderr, "FAIL %s: written=%lu\n", name, (unsigned long)written);
            ++failures;
        }
        if (memcmp(output, expected, sizeof(output)) != 0) {
            fprintf(stderr, "FAIL %s: digest mismatch\n", name);
            ++failures;
        }
    }
}

