static int failures = 0;

static void expect_status(const char *name, ano_crypto_status_t got, ano_crypto_status_t expected)
{
    if (got != expected) {
        fprintf(stderr, "FAIL %s: got %s expected %s\n", name,
                ano_crypto_status_name(got), ano_crypto_status_name(expected));
        ++failures;
    }
}

static int bytes_equal(const uint8_t *a, const uint8_t *b, size_t len)
{
    uint8_t diff = 0u;
    size_t i;
    for (i = 0u; i < len; ++i) {
        diff = (uint8_t)(diff | (uint8_t)(a[i] ^ b[i]));
    }
    return diff == 0u;
}

static void expect_bytes(const char *name, const uint8_t *got, const uint8_t *expected, size_t len)
{
    if (!bytes_equal(got, expected, len)) {
        fprintf(stderr, "FAIL %s: output mismatch\n", name);
        ++failures;
    }
}

static void test_aes_primitive(void)
{
    static const uint8_t plaintext[16] = {
        0x00u,0x11u,0x22u,0x33u,0x44u,0x55u,0x66u,0x77u,
        0x88u,0x99u,0xaau,0xbbu,0xccu,0xddu,0xeeu,0xffu
    };
    static const uint8_t keys[3][32] = {
        {0x00u,0x01u,0x02u,0x03u,0x04u,0x05u,0x06u,0x07u,
         0x08u,0x09u,0x0au,0x0bu,0x0cu,0x0du,0x0eu,0x0fu},
        {0x00u,0x01u,0x02u,0x03u,0x04u,0x05u,0x06u,0x07u,
         0x08u,0x09u,0x0au,0x0bu,0x0cu,0x0du,0x0eu,0x0fu,
         0x10u,0x11u,0x12u,0x13u,0x14u,0x15u,0x16u,0x17u},
        {0x00u,0x01u,0x02u,0x03u,0x04u,0x05u,0x06u,0x07u,
         0x08u,0x09u,0x0au,0x0bu,0x0cu,0x0du,0x0eu,0x0fu,
         0x10u,0x11u,0x12u,0x13u,0x14u,0x15u,0x16u,0x17u,
         0x18u,0x19u,0x1au,0x1bu,0x1cu,0x1du,0x1eu,0x1fu}
    };
    static const size_t key_lens[3] = {16u, 24u, 32u};
    static const uint8_t expected[3][16] = {
        {0x69u,0xc4u,0xe0u,0xd8u,0x6au,0x7bu,0x04u,0x30u,
         0xd8u,0xcdu,0xb7u,0x80u,0x70u,0xb4u,0xc5u,0x5au},
        {0xddu,0xa9u,0x7cu,0xa4u,0x86u,0x4cu,0xdfu,0xe0u,
         0x6eu,0xafu,0x70u,0xa0u,0xecu,0x0du,0x71u,0x91u},
        {0x8eu,0xa2u,0xb7u,0xcau,0x51u,0x67u,0x45u,0xbfu,
         0xeau,0xfcu,0x49u,0x90u,0x4bu,0x49u,0x60u,0x89u}
    };
    size_t i;
    for (i = 0u; i < 3u; ++i) {
        ano_crypto_internal_aes_ctx_t ctx;
        uint8_t out[16];
        uint8_t recovered[16];
        expect_status("aes primitive init", ano_crypto_internal_aes_init(&ctx, keys[i], key_lens[i]), ANO_CRYPTO_OK);
        expect_status("aes primitive encrypt", ano_crypto_internal_aes_encrypt_block(&ctx, plaintext, out), ANO_CRYPTO_OK);
        expect_bytes("aes primitive ciphertext", out, expected[i], sizeof(out));
        expect_status("aes primitive decrypt", ano_crypto_internal_aes_decrypt_block(&ctx, out, recovered), ANO_CRYPTO_OK);
        expect_bytes("aes primitive plaintext", recovered, plaintext, sizeof(recovered));
        ano_crypto_internal_aes_uninit(&ctx);
        (void)ano_crypto_csp_zeroize(out, sizeof(out));
        (void)ano_crypto_csp_zeroize(recovered, sizeof(recovered));
    }
}

static void test_cbc_vector(const uint8_t *key, size_t key_len, const uint8_t expected[64])
{
    static const uint8_t iv[16] = {
        0x00u,0x01u,0x02u,0x03u,0x04u,0x05u,0x06u,0x07u,
        0x08u,0x09u,0x0au,0x0bu,0x0cu,0x0du,0x0eu,0x0fu
    };
    static const uint8_t plaintext[64] = {
        0x6bu,0xc1u,0xbeu,0xe2u,0x2eu,0x40u,0x9fu,0x96u,0xe9u,0x3du,0x7eu,0x11u,0x73u,0x93u,0x17u,0x2au,
        0xaeu,0x2du,0x8au,0x57u,0x1eu,0x03u,0xacu,0x9cu,0x9eu,0xb7u,0x6fu,0xacu,0x45u,0xafu,0x8eu,0x51u,
        0x30u,0xc8u,0x1cu,0x46u,0xa3u,0x5cu,0xe4u,0x11u,0xe5u,0xfbu,0xc1u,0x19u,0x1au,0x0au,0x52u,0xefu,
        0xf6u,0x9fu,0x24u,0x45u,0xdfu,0x4fu,0x9bu,0x17u,0xadu,0x2bu,0x41u,0x7bu,0xe6u,0x6cu,0x37u,0x10u
    };
    ano_crypto_csp_handle_t handle = ANO_CRYPTO_CSP_INVALID_HANDLE;
    uint8_t out[64];
    uint8_t recovered[64];
    uint8_t inplace[64];
    uint8_t *ctx = 0;
    size_t ctx_size = 0u;
    size_t written = 0u;

    expect_status("aes key import", ano_crypto_key_import_secret(ANO_CRYPTO_KEY_TYPE_BLOCK_CIPHER, key, key_len, ANO_CRYPTO_KEY_FLAG_NONE, &handle), ANO_CRYPTO_OK);
    expect_status("cbc encrypt oneshot", ano_crypto_cipher_crypt_with_key(ANO_CRYPTO_CIPHER_ALG_AES, ANO_CRYPTO_CIPHER_MODE_CBC, ANO_CRYPTO_CIPHER_DIRECTION_ENCRYPT, handle, iv, sizeof(iv), plaintext, sizeof(plaintext), out, sizeof(out), &written, ANO_CRYPTO_CIPHER_FLAG_NONE), ANO_CRYPTO_OK);
    if (written != sizeof(plaintext)) { ++failures; }
    expect_bytes("cbc ciphertext", out, expected, sizeof(out));

    written = 0u;
    expect_status("cbc decrypt oneshot", ano_crypto_cipher_crypt_with_key(ANO_CRYPTO_CIPHER_ALG_AES, ANO_CRYPTO_CIPHER_MODE_CBC, ANO_CRYPTO_CIPHER_DIRECTION_DECRYPT, handle, iv, sizeof(iv), out, sizeof(out), recovered, sizeof(recovered), &written, ANO_CRYPTO_CIPHER_FLAG_NONE), ANO_CRYPTO_OK);
    expect_bytes("cbc recovered", recovered, plaintext, sizeof(recovered));

    expect_status("cipher context size", ano_crypto_cipher_context_size(ANO_CRYPTO_CIPHER_ALG_AES, ANO_CRYPTO_CIPHER_MODE_CBC, &ctx_size), ANO_CRYPTO_OK);
    ctx = (uint8_t *)calloc(1u, ctx_size);
    if (ctx == 0) { ++failures; goto cleanup; }
    memcpy(inplace, plaintext, sizeof(inplace));
    expect_status("cbc streaming init", ano_crypto_cipher_init(ctx, ctx_size, ANO_CRYPTO_CIPHER_ALG_AES, ANO_CRYPTO_CIPHER_MODE_CBC, ANO_CRYPTO_CIPHER_DIRECTION_ENCRYPT, handle, iv, sizeof(iv), ANO_CRYPTO_CIPHER_FLAG_NONE), ANO_CRYPTO_OK);
    written = 0u;
    expect_status("cbc streaming block", ano_crypto_cipher_update(ctx, inplace, 16u, inplace, sizeof(inplace), &written), ANO_CRYPTO_OK);
    expect_status("cbc streaming rest", ano_crypto_cipher_update(ctx, inplace + 16u, 48u, inplace + 16u, 48u, &written), ANO_CRYPTO_OK);
    expect_bytes("cbc in-place ciphertext", inplace, expected, sizeof(inplace));
    expect_status("cbc uninit", ano_crypto_cipher_uninit(ctx, ctx_size), ANO_CRYPTO_OK);

cleanup:
    if (ctx != 0) { free(ctx); }
    expect_status("aes key destroy", ano_crypto_key_destroy(handle), ANO_CRYPTO_OK);
    (void)ano_crypto_csp_zeroize(out, sizeof(out));
    (void)ano_crypto_csp_zeroize(recovered, sizeof(recovered));
    (void)ano_crypto_csp_zeroize(inplace, sizeof(inplace));
}

