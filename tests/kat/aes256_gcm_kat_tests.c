static int failures = 0;

static void expect_status(const char *name, ano_crypto_status_t got, ano_crypto_status_t expected)
{
    if (got != expected) {
        fprintf(stderr, "FAIL %s: got %s expected %s\n", name,
                ano_crypto_status_name(got), ano_crypto_status_name(expected));
        ++failures;
    }
}

static void expect_bytes(const char *name, const uint8_t *got, const uint8_t *expected, size_t len)
{
    uint8_t diff = 0u;
    size_t i;
    for (i = 0u; i < len; ++i) diff = (uint8_t)(diff | (uint8_t)(got[i] ^ expected[i]));
    if (diff != 0u) {
        fprintf(stderr, "FAIL %s: byte mismatch\n", name);
        ++failures;
    }
}

static ano_crypto_csp_handle_t import_key(const uint8_t key[32])
{
    ano_crypto_csp_handle_t handle = ANO_CRYPTO_CSP_INVALID_HANDLE;
    expect_status("key import", ano_crypto_key_import_secret(
        ANO_CRYPTO_KEY_TYPE_BLOCK_CIPHER, key, 32u, ANO_CRYPTO_KEY_FLAG_NONE, &handle), ANO_CRYPTO_OK);
    return handle;
}

static void run_vector(
    const char *name,
    const uint8_t key[32],
    const uint8_t nonce[12],
    const uint8_t *aad,
    size_t aad_len,
    const uint8_t *plaintext,
    size_t plaintext_len,
    const uint8_t *expected_ciphertext,
    const uint8_t expected_tag[16])
{
    ano_crypto_csp_handle_t handle = import_key(key);
    uint8_t ciphertext[128];
    uint8_t recovered[128];
    uint8_t tag[16];
    size_t written = 99u;

    memset(ciphertext, 0xa5, sizeof(ciphertext));
    memset(recovered, 0xa5, sizeof(recovered));
    memset(tag, 0xa5, sizeof(tag));
    expect_status(name, ano_crypto_aes256_gcm_encrypt(
        handle, nonce, 12u, aad, aad_len, plaintext, plaintext_len,
        ciphertext, plaintext_len, &written, tag, sizeof(tag)), ANO_CRYPTO_OK);
    if (written != plaintext_len) { fprintf(stderr, "FAIL %s: encrypt length\n", name); ++failures; }
    expect_bytes("ciphertext", ciphertext, expected_ciphertext, plaintext_len);
    expect_bytes("tag", tag, expected_tag, sizeof(tag));

    written = 99u;
    expect_status(name, ano_crypto_aes256_gcm_decrypt(
        handle, nonce, 12u, aad, aad_len, ciphertext, plaintext_len,
        tag, sizeof(tag), recovered, plaintext_len, &written), ANO_CRYPTO_OK);
    if (written != plaintext_len) { fprintf(stderr, "FAIL %s: decrypt length\n", name); ++failures; }
    expect_bytes("plaintext", recovered, plaintext, plaintext_len);

    if (plaintext_len != 0u) {
        memcpy(recovered, plaintext, plaintext_len);
        written = 0u;
        expect_status("exact in-place encrypt", ano_crypto_aes256_gcm_encrypt(
            handle, nonce, 12u, aad, aad_len, recovered, plaintext_len,
            recovered, plaintext_len, &written, tag, sizeof(tag)), ANO_CRYPTO_OK);
        expect_bytes("in-place ciphertext", recovered, expected_ciphertext, plaintext_len);
        written = 0u;
        expect_status("exact in-place decrypt", ano_crypto_aes256_gcm_decrypt(
            handle, nonce, 12u, aad, aad_len, recovered, plaintext_len,
            tag, sizeof(tag), recovered, plaintext_len, &written), ANO_CRYPTO_OK);
        expect_bytes("in-place plaintext", recovered, plaintext, plaintext_len);
    }
    expect_status("key destroy", ano_crypto_key_destroy(handle), ANO_CRYPTO_OK);
}

